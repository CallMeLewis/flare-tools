//! Keeps each build's outcome and log on disk, so earlier builds can be looked at again.
//!
//! Layout: `<config dir>/builds/<mod id>/<started at>.json` holds the record and
//! `<started at>.log.json` the lines, kept apart so listing builds doesn't read every log.

use std::fs;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

use crate::build::{BuildOutcome, BuiltPbo, Level, Step, StepStatus};

/// The folder build records live in.
pub struct Dir(pub PathBuf);

/// Builds kept per mod. Older ones go, along with their logs.
const KEEP: usize = 30;

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct LogLine {
    pub level: Level,
    pub text: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct StepRecord {
    pub step: Step,
    pub status: StepStatus,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BuildRecord {
    pub id: String,
    pub started_at: u64,
    pub finished_at: u64,
    pub ok: bool,
    pub cancelled: bool,
    pub duration_ms: u64,
    pub signed: bool,
    pub pbos: Vec<BuiltPbo>,
    pub warnings: Vec<String>,
    pub error: Option<String>,
    pub steps: Vec<StepRecord>,
    /// How long the log is, so the list can say without reading it.
    pub log_lines: usize,
}

/// Everything a build showed as it ran, besides its outcome.
#[derive(Default)]
pub struct Capture {
    pub log: Vec<LogLine>,
    pub steps: Vec<StepRecord>,
}

impl Capture {
    pub fn log(&mut self, level: Level, text: &str) {
        self.log.push(LogLine { level, text: text.to_string() });
    }

    /// Keeps one entry per step, holding its latest status.
    pub fn step(&mut self, step: Step, status: StepStatus) {
        self.steps.retain(|s| s.step != step);
        self.steps.push(StepRecord { step, status });
    }
}

/// Mod ids are generated by the app, but keep anything odd out of the path all the same. An id with
/// nothing left would name the folder holding every mod's builds, so it has no folder.
fn mod_folder(dir: &Dir, mod_id: &str) -> Option<PathBuf> {
    let safe: String = mod_id.chars().filter(|c| c.is_ascii_alphanumeric() || *c == '-' || *c == '_').collect();
    (!safe.is_empty()).then(|| dir.0.join(safe))
}

fn valid_build_id(id: &str) -> bool {
    !id.is_empty() && id.chars().all(|c| c.is_ascii_digit())
}

fn write_json<T: Serialize>(path: &Path, value: &T) -> Result<(), String> {
    let text = serde_json::to_string(value).map_err(|e| e.to_string())?;
    fs::write(path, text).map_err(|e| format!("Couldn't save the build record: {e}"))
}

pub fn save(
    dir: &Dir,
    mod_id: &str,
    started_at: u64,
    outcome: &BuildOutcome,
    capture: Capture,
) -> Result<BuildRecord, String> {
    let folder = mod_folder(dir, mod_id).ok_or("That mod has no id.")?;
    fs::create_dir_all(&folder).map_err(|e| format!("Couldn't create {}: {e}", folder.display()))?;
    let id = started_at.to_string();
    let record = BuildRecord {
        id: id.clone(),
        started_at,
        finished_at: outcome.finished_at,
        ok: outcome.ok,
        cancelled: outcome.cancelled,
        duration_ms: outcome.duration_ms,
        signed: outcome.signed,
        pbos: outcome.pbos.clone(),
        warnings: outcome.warnings.clone(),
        error: outcome.error.clone(),
        steps: capture.steps,
        log_lines: capture.log.len(),
    };
    write_json(&folder.join(format!("{id}.log.json")), &capture.log)?;
    write_json(&folder.join(format!("{id}.json")), &record)?;
    prune(&folder);
    Ok(record)
}

/// A mod's builds, newest first.
pub fn list(dir: &Dir, mod_id: &str) -> Vec<BuildRecord> {
    let Some(folder) = mod_folder(dir, mod_id) else { return Vec::new() };
    let mut records: Vec<BuildRecord> = fs::read_dir(&folder)
        .into_iter()
        .flatten()
        .flatten()
        .filter(|entry| {
            let name = entry.file_name();
            let name = name.to_string_lossy();
            name.ends_with(".json") && !name.ends_with(".log.json")
        })
        .filter_map(|entry| fs::read_to_string(entry.path()).ok())
        .filter_map(|text| serde_json::from_str(&text).ok())
        .collect();
    records.sort_by_key(|a| std::cmp::Reverse(a.started_at));
    records
}

pub fn log(dir: &Dir, mod_id: &str, build_id: &str) -> Result<Vec<LogLine>, String> {
    if !valid_build_id(build_id) {
        return Err("That build doesn't exist.".into());
    }
    let path = mod_folder(dir, mod_id).ok_or("That build doesn't exist.")?.join(format!("{build_id}.log.json"));
    let text = fs::read_to_string(path).map_err(|_| "That build's log is no longer here.".to_string())?;
    serde_json::from_str(&text).map_err(|e| format!("Couldn't read the build log: {e}"))
}

/// Drops everything kept for a mod, for when it's removed from the list.
pub fn remove(dir: &Dir, mod_id: &str) {
    if let Some(folder) = mod_folder(dir, mod_id) {
        let _ = fs::remove_dir_all(folder);
    }
}

fn prune(folder: &Path) {
    let mut ids: Vec<u64> = fs::read_dir(folder)
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|entry| {
            let name = entry.file_name();
            let name = name.to_string_lossy();
            name.strip_suffix(".json").filter(|n| !n.ends_with(".log")).and_then(|n| n.parse().ok())
        })
        .collect();
    ids.sort_unstable_by(|a, b| b.cmp(a));
    for id in ids.into_iter().skip(KEEP) {
        let _ = fs::remove_file(folder.join(format!("{id}.json")));
        let _ = fs::remove_file(folder.join(format!("{id}.log.json")));
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn an_id_with_nothing_safe_in_it_removes_nothing() {
        let root = std::env::temp_dir().join(format!("flare-tools-history-{}", std::process::id()));
        fs::create_dir_all(root.join("mod-1")).unwrap();
        let dir = Dir(root.clone());
        for id in ["", "../..", "./"] {
            remove(&dir, id);
        }
        assert!(root.join("mod-1").is_dir());
        fs::remove_dir_all(root).unwrap();
    }
}
